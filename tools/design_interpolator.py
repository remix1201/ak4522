"""Design the 8x interpolation filter and write its coefficients and report.

Linear-phase FIR designed by linear programming. Constraints come straight
from the datasheet filter table, scaled to the DAC rate (they are the same
in normalized frequency at every rate, D-F08):

  * passband 0 to 20/44.1 fs within +/-RIPPLE_DB of the 1 kHz response (D-F04)
  * response at 20/44.1 fs equal to EDGE_DB relative to 1 kHz (D-F01)
  * response at 0.5 fs equal to -6.0 dB relative to 1 kHz (D-F02)
  * from 24.1/44.1 fs to the 8x Nyquist frequency, the largest magnitude is
    minimized (D-F03, D-F05)

The length is the shortest odd length whose measured stopband attenuation
reaches MIN_STOPBAND_DB. The rest of the 14.7-frame delay is modeled
elsewhere as an explicit pipeline delay (P-87). The coefficients are fitted:
they are not AKM's coefficients.

    cd tools && uv run python design_interpolator.py

Writes src/dsp/interpolator_coefficients.inc and
src/dsp/interpolator_design.json.
"""

from __future__ import annotations

import hashlib
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import linprog

from ak4522_tools import dac_gates

OVERSAMPLING = 8
REFERENCE_RATE = 44100.0          # design in Hz at this rate; normalized use at any rate
FS_HIGH = OVERSAMPLING * REFERENCE_RATE
PASSBAND_HZ = 20000.0             # D-F01
HALF_HZ = 22050.0                 # D-F02
STOPBAND_HZ = 24100.0             # D-F03
RIPPLE_DB = 0.058                 # P-88: inside the 0.06 dB limit (D-F04)
EDGE_DB = -0.058                  # P-88: inside -0.06 +/- 0.01 dB (D-F01, P-80)
HALF_DB = -6.0                    # D-F02
MIN_STOPBAND_DB = 43.2            # P-88: 43 dB minimum (D-F05) plus measurement margin
PASSBAND_GRID = 800
STOPBAND_GRID = 4000
SEARCH_START = 175

ROOT = Path(__file__).resolve().parent.parent
OUT_INC = ROOT / "src/dsp/interpolator_coefficients.inc"
OUT_JSON = ROOT / "src/dsp/interpolator_design.json"


def cosine_basis(freqs: np.ndarray, half_order: int) -> np.ndarray:
    """Amplitude basis of an odd-length symmetric FIR: A(f) = a0 + sum 2 ak cos(2 pi f k / fs)."""
    k = np.arange(half_order + 1)
    basis = 2.0 * np.cos(2.0 * np.pi * np.outer(np.atleast_1d(freqs), k) / FS_HIGH)
    basis[:, 0] = 1.0
    return basis


def design(length: int) -> np.ndarray | None:
    """LP design for one odd length; returns taps with unity gain at 1 kHz, or None."""
    m = (length - 1) // 2
    fp = np.linspace(0.0, PASSBAND_HZ, PASSBAND_GRID)
    fs = np.linspace(STOPBAND_HZ, FS_HIGH / 2.0, STOPBAND_GRID)
    upper = 10.0 ** (RIPPLE_DB / 20.0)
    lower = 10.0 ** (-RIPPLE_DB / 20.0)
    P = cosine_basis(fp, m)
    S = cosine_basis(fs, m)
    zp = np.zeros((fp.size, 1))
    ones = np.ones((fs.size, 1))
    # Variables: amplitude coefficients a0..am, then the stopband bound d.
    a_ub = np.vstack([np.hstack([P, zp]), np.hstack([-P, zp]),
                      np.hstack([S, -ones]), np.hstack([-S, -ones])])
    b_ub = np.concatenate([np.full(fp.size, upper), np.full(fp.size, -lower),
                           np.zeros(fs.size), np.zeros(fs.size)])
    a_eq = np.hstack([cosine_basis(np.array([1000.0, PASSBAND_HZ, HALF_HZ]), m), np.zeros((3, 1))])
    b_eq = np.array([1.0, 10.0 ** (EDGE_DB / 20.0), 10.0 ** (HALF_DB / 20.0)])
    cost = np.zeros(m + 2)
    cost[-1] = 1.0
    result = linprog(cost, A_ub=a_ub, b_ub=b_ub, A_eq=a_eq, b_eq=b_eq,
                     bounds=[(None, None)] * (m + 2), method="highs")
    if result.status != 0:
        return None
    a = result.x[:m + 1]
    return np.concatenate([a[:0:-1], a])


def hex_literal(value: float) -> str:
    """C++17 hexadecimal floating literal; exact for every double."""
    return float(value).hex()


def write_outputs(taps: np.ndarray, checks: list, searched: list) -> None:
    raw = np.ascontiguousarray(taps, dtype="<f8").tobytes()
    digest = hashlib.sha256(raw).hexdigest()
    OUT_INC.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Generated by tools/design_interpolator.py. Do not edit.",
        f"// {taps.size} taps at 8x, linear phase, unity gain at 1 kHz after 8x interpolation.",
        f"// SHA-256 of the little-endian doubles: {digest}",
        "// Fitted to the datasheet filter table; not AKM's coefficients (P-87, P-88).",
    ]
    lines += [f"{hex_literal(v)}, // {v:+.17e}" for v in taps]
    OUT_INC.write_text("\n".join(lines) + "\n", encoding="utf-8")

    report = {
        "generator": "tools/design_interpolator.py",
        "method": "linear program (scipy.optimize.linprog, HiGHS): minimize stopband peak "
                  "subject to passband ripple, edge, and half-rate equality constraints",
        "parameters": {
            "oversampling": OVERSAMPLING, "reference_rate_hz": REFERENCE_RATE,
            "passband_hz": PASSBAND_HZ, "half_hz": HALF_HZ, "stopband_hz": STOPBAND_HZ,
            "ripple_db": RIPPLE_DB, "edge_db": EDGE_DB, "half_db": HALF_DB,
            "min_stopband_db": MIN_STOPBAND_DB, "passband_grid": PASSBAND_GRID,
            "stopband_grid": STOPBAND_GRID,
        },
        "length": int(taps.size),
        "delay_samples_8x": (taps.size - 1) / 2,
        "delay_dac_frames": (taps.size - 1) / 2 / OVERSAMPLING,
        "precision": "IEEE 754 double",
        "sha256_le_f8": digest,
        "lengths_searched": searched,
        "measured": [c.__dict__ for c in checks],
        "versions": {"python": sys.version.split()[0], "numpy": np.__version__,
                     "scipy": scipy.__version__, "platform": platform.platform()},
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    searched = []
    for length in range(SEARCH_START, 401, 2):
        taps = design(length)
        if taps is None:
            searched.append({"length": length, "feasible": False})
            continue
        h = taps * OVERSAMPLING  # zero-stuffing gain: unity at 1 kHz after interpolation
        checks = dac_gates.digital_filter_checks(h, FS_HIGH, REFERENCE_RATE, check_delay=False)
        stop = next(c for c in checks if c.name == "stopband_attenuation_db").value
        searched.append({"length": length, "feasible": True, "stopband_db": round(stop, 4)})
        if all(c.passed for c in checks) and stop >= MIN_STOPBAND_DB:
            write_outputs(h, checks, searched)
            print(f"length {length}: delay {(length - 1) / 16} DAC frames, stopband {stop:.3f} dB")
            for c in checks:
                print(f"  {c.name}: {c.value:.5f} ({'pass' if c.passed else 'FAIL'})")
            return 0
    print("no length up to 399 met the constraints", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
