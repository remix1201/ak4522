"""Design the analog reconstruction model and the pipeline delay.

The datasheet gives the DAC's analog filtering only as a second-order
switched-capacitor filter plus a second-order continuous-time filter
(D-03), with the combined digital-plus-analog response within +/-0.2 dB to
20 kHz (D-F07) and a 14.7-frame delay from input register to analog output
(D-F06). This script fits a model to those facts (P-89):

  * the chain is: interpolator, then PIPELINE_SAMPLES of pure delay at 8x
    (undocumented stages, P-87), then two second-order sections
  * the sections are a 4th-order Butterworth lowpass at the 8x rate
    (bilinear transform, prewarped at its cutoff), normalized to fs
  * the cutoff is solved so the chain's passband delay is exactly
    TARGET_DELAY_FRAMES

The sections are fitted, not AKM's analog circuit (U-03).

    cd tools && uv run python design_reconstruction.py

Writes src/dsp/reconstruction_coefficients.inc and
src/dsp/reconstruction_design.json.
"""

from __future__ import annotations

import hashlib
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy
from scipy import signal
from scipy.optimize import brentq

from ak4522_tools import dac_gates, response

OVERSAMPLING = 8
REFERENCE_RATE = 44100.0
FS_HIGH = OVERSAMPLING * REFERENCE_RATE
PIPELINE_SAMPLES = 21            # P-87, P-89: 2.625 DAC frames
TARGET_DELAY_FRAMES = 14.7       # D-F06
CUTOFF_SEARCH_HZ = (30000.0, 170000.0)
TAIL_SAMPLES = 6000              # enough for the sections to decay below 1e-15

ROOT = Path(__file__).resolve().parent.parent
INTERPOLATOR_INC = ROOT / "src/dsp/interpolator_coefficients.inc"
OUT_INC = ROOT / "src/dsp/reconstruction_coefficients.inc"
OUT_JSON = ROOT / "src/dsp/reconstruction_design.json"


def read_inc(path: Path) -> np.ndarray:
    values = []
    for line in path.read_text(encoding="utf-8").splitlines():
        literal = line.split("//")[0].strip().rstrip(",")
        if literal:
            values.append(float.fromhex(literal))
    return np.array(values)


def sections(cutoff_hz: float) -> np.ndarray:
    return signal.butter(4, cutoff_hz, fs=FS_HIGH, output="sos")


def chain_response(interpolator: np.ndarray, cutoff_hz: float) -> np.ndarray:
    x = np.concatenate([np.zeros(PIPELINE_SAMPLES), interpolator, np.zeros(TAIL_SAMPLES)])
    return signal.sosfilt(sections(cutoff_hz), x)


def chain_delay_frames(interpolator: np.ndarray, cutoff_hz: float) -> float:
    h = chain_response(interpolator, cutoff_hz)
    fit = response.passband_delay(h, FS_HIGH, dac_gates.REFERENCE_HZ,
                                  dac_gates.band_edges(REFERENCE_RATE).passband_hz)
    return fit.delay_samples / OVERSAMPLING


def main() -> int:
    interpolator = read_inc(INTERPOLATOR_INC)
    cutoff = brentq(lambda f: chain_delay_frames(interpolator, f) - TARGET_DELAY_FRAMES,
                    *CUTOFF_SEARCH_HZ, xtol=1e-6, rtol=1e-14)
    sos = sections(cutoff)
    poles = np.concatenate([np.roots(s[3:]) for s in sos])
    if np.max(np.abs(poles)) >= 1.0:
        print("unstable design", file=sys.stderr)
        return 1

    h = chain_response(interpolator, cutoff)
    core = dac_gates.core_checks(h, FS_HIGH, REFERENCE_RATE)
    fit = response.passband_delay(h, FS_HIGH, dac_gates.REFERENCE_HZ,
                                  dac_gates.band_edges(REFERENCE_RATE).passband_hz)
    probe_hz = [20000.0, 44100.0, 100000.0, 150000.0]
    section_db = 20 * np.log10(np.abs(signal.sosfreqz(sos, worN=probe_hz, fs=FS_HIGH)[1]))

    # b0 b1 b2 a1 a2 per section (a0 = 1).
    flat = [float(v) for s in sos for v in (s[0], s[1], s[2], s[4], s[5])]
    digest = hashlib.sha256(np.array(flat, dtype="<f8").tobytes()).hexdigest()
    lines = [
        "// Generated by tools/design_reconstruction.py. Do not edit.",
        f"// Two biquad sections, b0 b1 b2 a1 a2 each (a0 = 1); cutoff {cutoff / REFERENCE_RATE:.9f} fs.",
        f"// SHA-256 of the little-endian doubles: {digest}",
        "// Fitted reconstruction model; not AKM's analog circuit (P-89, U-03).",
    ]
    lines += [f"{v.hex()}, // {v:+.17e}" for v in flat]
    OUT_INC.write_text("\n".join(lines) + "\n", encoding="utf-8")

    report = {
        "generator": "tools/design_reconstruction.py",
        "model": "pipeline delay then 4th-order Butterworth lowpass as two biquads at 8x, "
                 "bilinear transform prewarped at the cutoff, normalized to fs",
        "pipeline_samples_8x": PIPELINE_SAMPLES,
        "pipeline_dac_frames": PIPELINE_SAMPLES / OVERSAMPLING,
        "cutoff_fs": cutoff / REFERENCE_RATE,
        "cutoff_hz_at_44100": cutoff,
        "target_delay_frames": TARGET_DELAY_FRAMES,
        "measured_delay_frames": fit.delay_samples / OVERSAMPLING,
        "dispersion_frames": fit.max_deviation_samples / OVERSAMPLING,
        "pole_radius_max": float(np.max(np.abs(poles))),
        "section_response_db": dict(zip([f"{f:.0f}_hz_at_44100" for f in probe_hz],
                                        [round(float(v), 4) for v in section_db])),
        "core_checks": [c.__dict__ for c in core],
        "precision": "IEEE 754 double",
        "sha256_le_f8": digest,
        "versions": {"python": sys.version.split()[0], "numpy": np.__version__,
                     "scipy": scipy.__version__, "platform": platform.platform()},
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    print(f"cutoff {cutoff:.3f} Hz ({cutoff / REFERENCE_RATE:.6f} fs), "
          f"delay {fit.delay_samples / OVERSAMPLING:.6f} frames, max pole radius {np.max(np.abs(poles)):.6f}")
    for c in core:
        print(f"  {c.name}: {c.value:.5f} ({'pass' if c.passed else 'FAIL'})")
    return 0 if all(c.passed for c in core) else 1


if __name__ == "__main__":
    sys.exit(main())
