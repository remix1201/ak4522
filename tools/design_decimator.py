"""Design the ADC's 8x decimation filter and write its coefficients and report.

Linear-phase FIR designed by linear programming, from the datasheet filter
table scaled to the ADC rate (frequencies scale with fs, AD-07):

  * passband 0 to 19.76/44.1 fs within +/-RIPPLE_DB of the 1 kHz response (AD-03, AD-04)
  * -0.02 dB at 20.02/44.1 fs, -0.06 dB at 20.20/44.1 fs, -6.0 dB at 0.5 fs (AD-03)
  * from 24.34/44.1 fs to the 8x Nyquist frequency, the largest magnitude is
    minimized; it must reach MIN_STOPBAND_DB (AD-04)

The filter has an even length (type II), so its delay is a whole number of
8x samples plus one half; a pipeline delay of whole 8x samples brings the
total to 234.5 samples, 29.3125 ADC frames, the nearest such value to the
nominal 29.3 (AD-05, P-105). The length is the shortest even length whose
stopband reaches MIN_STOPBAND_DB. The coefficients are fitted: they are not
AKM's coefficients.

    cd tools && uv run python design_decimator.py

Writes src/dsp/decimator_coefficients.inc and src/dsp/decimator_design.json.
"""

from __future__ import annotations

import hashlib
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy
from scipy.optimize import linprog

from ak4522_tools import adc_gates

OVERSAMPLING = 8
REFERENCE_RATE = 44100.0
FS_HIGH = OVERSAMPLING * REFERENCE_RATE
RIPPLE_HZ = 19760.0          # AD-03
POINT_02_HZ = 20020.0        # AD-03
POINT_06_HZ = 20200.0        # AD-03
HALF_HZ = 22050.0            # AD-03
STOPBAND_HZ = 24340.0        # AD-04
RIPPLE_DB = 0.0048           # P-105: inside the 0.005 dB limit (AD-04)
MIN_STOPBAND_DB = 80.3       # P-105: 80 dB minimum (AD-04) plus measurement margin
TOTAL_DELAY_SAMPLES = 234.5  # P-105: 29.3125 frames, nearest half sample to 29.3 x 8
PASSBAND_GRID = 1000
STOPBAND_GRID = 12000
SEARCH_START = 300
SEARCH_END = 468             # longest even length the delay budget allows

ROOT = Path(__file__).resolve().parent.parent
OUT_INC = ROOT / "src/dsp/decimator_coefficients.inc"
OUT_JSON = ROOT / "src/dsp/decimator_design.json"


def cosine_basis(freqs: np.ndarray, half: int) -> np.ndarray:
    """Amplitude basis of an even-length symmetric FIR: A(f) = sum 2 b_k cos(2 pi f (k + 1/2) / fs)."""
    k = np.arange(half) + 0.5
    return 2.0 * np.cos(2.0 * np.pi * np.outer(np.atleast_1d(freqs), k) / FS_HIGH)


def db_to_gain(db: float) -> float:
    return 10.0 ** (db / 20.0)


def design(length: int) -> np.ndarray | None:
    """LP design for one even length; returns taps with unity gain at 1 kHz, or None."""
    half = length // 2
    fp = np.linspace(0.0, RIPPLE_HZ, PASSBAND_GRID)
    ft = np.linspace(RIPPLE_HZ, POINT_06_HZ, 200)  # keep the edge region well behaved
    fs = np.linspace(STOPBAND_HZ, FS_HIGH / 2.0, STOPBAND_GRID)
    P = cosine_basis(fp, half)
    T = cosine_basis(ft, half)
    S = cosine_basis(fs, half)
    zp = np.zeros((fp.size, 1))
    zt = np.zeros((ft.size, 1))
    ones = np.ones((fs.size, 1))
    # Variables: b_0..b_{half-1}, then the stopband bound d.
    a_ub = np.vstack([np.hstack([P, zp]), np.hstack([-P, zp]),
                      np.hstack([T, zt]), np.hstack([-T, zt]),
                      np.hstack([S, -ones]), np.hstack([-S, -ones])])
    b_ub = np.concatenate([np.full(fp.size, db_to_gain(RIPPLE_DB)), np.full(fp.size, -db_to_gain(-RIPPLE_DB)),
                           np.full(ft.size, db_to_gain(RIPPLE_DB)), np.full(ft.size, -db_to_gain(-0.07)),
                           np.zeros(fs.size), np.zeros(fs.size)])
    points = np.array([1000.0, POINT_02_HZ, POINT_06_HZ, HALF_HZ])
    a_eq = np.hstack([cosine_basis(points, half), np.zeros((points.size, 1))])
    b_eq = np.array([1.0, db_to_gain(-0.02), db_to_gain(-0.06), db_to_gain(-6.0)])
    cost = np.zeros(half + 1)
    cost[-1] = 1.0
    result = linprog(cost, A_ub=a_ub, b_ub=b_ub, A_eq=a_eq, b_eq=b_eq,
                     bounds=[(None, None)] * (half + 1), method="highs")
    if result.status != 0:
        return None
    b = result.x[:half]
    return np.concatenate([b[::-1], b])


def hex_literal(value: float) -> str:
    """C++17 hexadecimal floating literal; exact for every double."""
    return float(value).hex()


def write_outputs(taps: np.ndarray, pipeline: int, checks: list, searched: list) -> None:
    raw = np.ascontiguousarray(taps, dtype="<f8").tobytes()
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        "// Generated by tools/design_decimator.py. Do not edit.",
        f"// {taps.size} taps at 8x the ADC rate, linear phase (even length), unity gain at 1 kHz.",
        f"// SHA-256 of the little-endian doubles: {digest}",
        "// Fitted to the datasheet filter table; not AKM's coefficients (P-105).",
    ]
    lines += [f"{hex_literal(v)}, // {v:+.17e}" for v in taps]
    OUT_INC.write_text("\n".join(lines) + "\n", encoding="utf-8")

    filter_delay = (taps.size - 1) / 2
    report = {
        "generator": "tools/design_decimator.py",
        "method": "linear program (scipy.optimize.linprog, HiGHS): minimize stopband peak "
                  "subject to passband ripple and point equality constraints; type II linear phase",
        "parameters": {
            "oversampling": OVERSAMPLING, "reference_rate_hz": REFERENCE_RATE,
            "ripple_hz": RIPPLE_HZ, "point_02_hz": POINT_02_HZ, "point_06_hz": POINT_06_HZ,
            "half_hz": HALF_HZ, "stopband_hz": STOPBAND_HZ, "ripple_db": RIPPLE_DB,
            "min_stopband_db": MIN_STOPBAND_DB, "passband_grid": PASSBAND_GRID,
            "stopband_grid": STOPBAND_GRID,
        },
        "length": int(taps.size),
        "filter_delay_samples_8x": filter_delay,
        "pipeline_samples_8x": pipeline,
        "total_delay_samples_8x": filter_delay + pipeline,
        "total_delay_adc_frames": (filter_delay + pipeline) / OVERSAMPLING,
        "precision": "IEEE 754 double",
        "sha256_le_f8": digest,
        "lengths_searched": searched,
        "measured": [c.__dict__ for c in checks],
        "versions": {"python": sys.version.split()[0], "numpy": np.__version__,
                     "scipy": scipy.__version__, "platform": platform.platform()},
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    searched = []
    for length in range(SEARCH_START, SEARCH_END + 1, 2):
        taps = design(length)
        if taps is None:
            searched.append({"length": length, "feasible": False})
            continue
        pipeline = int(round(TOTAL_DELAY_SAMPLES - (length - 1) / 2))
        checks = adc_gates.decimation_checks(taps, FS_HIGH, REFERENCE_RATE,
                                             delay_frames=pipeline / OVERSAMPLING)
        stop = next(c for c in checks if c.name == "stopband_attenuation_db").value
        searched.append({"length": length, "feasible": True, "stopband_db": round(stop, 4)})
        print(f"length {length}: stopband {stop:.3f} dB", flush=True)
        if all(c.passed for c in checks) and stop >= MIN_STOPBAND_DB:
            write_outputs(taps, pipeline, checks, searched)
            print(f"length {length}: filter delay {(length - 1) / 2} + pipeline {pipeline} samples "
                  f"= {((length - 1) / 2 + pipeline) / OVERSAMPLING} frames")
            for c in checks:
                print(f"  {c.name}: {c.value:.5f} ({'pass' if c.passed else 'FAIL'})")
            return 0
    print(f"no even length up to {SEARCH_END} met the constraints", file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
