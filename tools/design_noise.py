"""Calibrate the NominalAnalog noise density and write it for the C++ code.

White Gaussian noise with a one-sided power density N0 (full-scale units
squared per hertz, where a full-scale sine has RMS 1/sqrt 2) is added at the
analog output (P-94). N0 is set so the A-weighted S/N over 10 Hz to 20 kHz
equals the datasheet typical of 100 dB (D-A03):

    N0 = (1/2) * 10^(-100/10) / integral of |A(f)|^2 from 10 Hz to 20 kHz

The density is physical, so it is the same at every DAC rate. Synthetic: the
real noise spectrum is unknown (U-09); with this flat spectrum the CCIR-ARM
S/N is 97.3 dB against 96 dB typical (DISC-08).

    cd tools && uv run python design_noise.py

Writes src/analog/noise_density.inc.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

from ak4522_tools import metrics, weighting

TARGET_SNR_A_DB = 100.0  # D-A03, typical
OUT = Path(__file__).resolve().parent.parent / "src/analog/noise_density.inc"


def main() -> int:
    f = np.linspace(metrics.BAND[0], metrics.BAND[1], 2_000_001)
    a_power = np.trapezoid(10.0 ** (weighting.a_weighting_db(f) / 10.0), f)
    density = metrics.FULL_SCALE_RMS**2 * 10.0 ** (-TARGET_SNR_A_DB / 10.0) / a_power
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/design_noise.py. Do not edit.\n"
        f"// One-sided noise density, full-scale units^2 per Hz, for {TARGET_SNR_A_DB:.1f} dB\n"
        f"// A-weighted S/N (D-A03, P-94). Integral of |A|^2 over 10 Hz to 20 kHz: {a_power:.9e} Hz.\n"
        f"{density.hex()} // {density:.17e}\n", encoding="utf-8")
    print(f"density {density:.6e} per Hz (A-weighted bandwidth {a_power:.1f} Hz)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
