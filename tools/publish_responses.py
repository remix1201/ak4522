"""Measure the core and the wrapper responses and write docs/responses.md.

The core (DacCore) is measured from its impulse response at the 8x rate at
the datasheet's 44.1 kHz conditions. The wrapper (HostProcessor) is measured
end to end at host rates with sine fits. They are published separately, as
the M3 gate requires.

    cd tools && uv run python publish_responses.py ../build/release
"""

from __future__ import annotations

import subprocess
import sys
from datetime import date
from pathlib import Path

import numpy as np

from ak4522_tools import dac_gates, response

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/responses.md"
PAIRS = [(44100, 44100), (48000, 44100), (96000, 44100), (192000, 48000), (44100, 48000),
         (88200, 32000), (48000, 37800)]
FREQS = [20.0, 100.0, 1000.0, 5000.0, 10000.0, 15000.0, 19000.0, 20000.0]


def core_section(build: Path) -> list[str]:
    ir = build / "dsp/publish_dac_core_impulse.txt"
    ir.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(build / "ak4522_impulse_dump"), "dac-core", str(ir), "1000"], check=True)
    h = np.loadtxt(ir)
    fs_high = 8 * dac_gates.DATASHEET_RATE
    checks = dac_gates.digital_filter_checks(h, fs_high, dac_gates.DATASHEET_RATE)
    checks.append(dac_gates.combined_response_check(h, fs_high, dac_gates.DATASHEET_RATE))
    lines = ["## Core (`DacCore`)", "",
             "Impulse response at 8 x 44.1 kHz through the public API, measured by "
             "`tools/analyze_response.py` against 1 kHz (D-F09).", "",
             "| Check | Value | Limit | Source | Result |", "| ----- | ----: | ----- | ------ | ------ |"]
    for c in checks:
        lines.append(f"| {c.name} | {c.value:.5f} | {c.limit} | {c.source} | {'pass' if c.passed else 'FAIL'} |")
    lines += ["", "| Frequency (Hz) | Gain (dB re 1 kHz) |", "| -------------: | -----------------: |"]
    for f, g in zip(FREQS, response.relative_db(h, fs_high, FREQS, dac_gates.REFERENCE_HZ)):
        lines.append(f"| {f:.0f} | {g:+.4f} |")
    return lines


def wrapper_section(build: Path) -> list[str]:
    lines = ["## Wrapper (`HostProcessor`)", "",
             "End-to-end response at the host rate, measured with least-squares sine fits by "
             "`ak4522_host_response` (gain relative to 1 kHz; phase delay in host frames). It includes "
             "both sample-rate converters and the latency alignment. Frequencies at or above the lower "
             "rate's passband edge (20/44.1 of the lower rate) are omitted.", "",
             "The datasheet's filter values apply at 44.1 kHz against 1 kHz (D-F09). At other DAC "
             "rates the same filter response places 1 kHz at a different point of its passband ripple, "
             "so gains relative to 1 kHz can exceed 0.06 dB there; these values are informational. "
             "Single-frequency delays differ from the reported latency by up to the reconstruction "
             "dispersion (about 0.013 DAC frames); the passband average is within 0.01 frame (P-84).", ""]
    for host, dac in PAIRS:
        edge = 20.0 / 44.1 * min(host, dac)
        freqs = [f for f in FREQS if f <= edge + 1e-6]
        out = subprocess.run([str(build / "ak4522_host_response"), str(host), str(dac)]
                             + [str(f) for f in freqs], check=True, capture_output=True, text=True).stdout
        rows = [l.split(",") for l in out.strip().splitlines()]
        latency = int(rows[0][1])
        lines += [f"### Host {host / 1000:g} kHz, DAC {dac / 1000:g} kHz", "",
                  f"Reported latency: {latency} host frames ({1e3 * latency / host:.3f} ms).", "",
                  "| Frequency (Hz) | Gain (dB re 1 kHz) | Phase delay (frames) | Delay minus latency |",
                  "| -------------: | -----------------: | -------------------: | ------------------: |"]
        for f, g, d in rows[1:]:
            lines.append(f"| {float(f):.0f} | {float(g):+.4f} | {float(d):.4f} | {float(d) - latency:+.4f} |")
        lines.append("")
    return lines


def main() -> int:
    build = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "build/release"
    lines = ["# Published responses", "",
             f"Generated by `tools/publish_responses.py` on {date.today().isoformat()}. "
             "Regenerate after any change to the signal path.", ""]
    lines += core_section(build) + [""] + wrapper_section(build)
    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
