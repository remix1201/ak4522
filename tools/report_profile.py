"""Measure the NominalAnalog profile against the datasheet and write
docs/analog_profile.md (M4 typical-target report).

Captures come from ak4522_capture through HostProcessor at 44.1 kHz host
and DAC rates, the conditions of [DS] p.5; metrics from metrics.py.

    cd tools && uv run python report_profile.py ../build/release
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

import numpy as np

from ak4522_tools import metrics, weighting

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/analog_profile.md"
RATE = 44100.0
TONE = 997.0


def capture(build: Path, work: Path, name: str, *args: str) -> np.ndarray:
    path = work / f"{name}.f64"
    subprocess.run([str(build / "ak4522_capture"), str(path), *args], check=True)
    return np.fromfile(path, dtype="<f8")


def main() -> int:
    build = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "build/release"
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        zero = capture(build, work, "zero", "--nominal", "--seconds", "10")
        dr20 = capture(build, work, "dr20", "--nominal", "--tone", str(TONE), "--level", "-60", "--seconds", "10")
        dr16 = capture(build, work, "dr16", "--nominal", "--bits16", "--tone", str(TONE), "--level", "-60",
                       "--seconds", "10")
        dr16d = capture(build, work, "dr16d", "--nominal", "--bits16", "--dither", "--tone", str(TONE),
                        "--level", "-60", "--seconds", "10")
        sweep = {lvl: capture(build, work, f"s{lvl}", "--nominal", "--tone", str(TONE), "--level", str(lvl),
                              "--seconds", "5") for lvl in (-60, -20, -6, -1, 0)}

    snr_a = metrics.snr_a(zero, RATE)
    snr_ccir = metrics.snr_ccir_arm(zero, RATE)
    snr_unweighted = 20 * np.log10(metrics.FULL_SCALE_RMS
                                   / weighting.rms(weighting.apply(zero, RATE, None, metrics.BAND)))
    rows = [
        ("S/(N+D), 0 dBFS", "D-A01", "80", "90", metrics.sinad(sweep[0], RATE, TONE), "90 +/- 1"),
        ("Dynamic range, -60 dBFS, A-weighted", "D-A02", "95", "100", metrics.dynamic_range(dr20, RATE, TONE), "100 +/- 1"),
        ("S/N, A-weighted", "D-A03", "95", "100", snr_a, "100 +/- 1"),
        ("S/N, CCIR-ARM", "D-A13", "-", "96", snr_ccir, "disclosed deviation (DISC-08)"),
        ("Dynamic range, 16-bit input, no dither", "D-A11", "-", "98", metrics.dynamic_range(dr16, RATE, TONE), "report"),
        ("Dynamic range, 16-bit input, TPDF dither", "D-A11", "-", "98", metrics.dynamic_range(dr16d, RATE, TONE), "report"),
    ]
    lines = [
        "# NominalAnalog profile report", "",
        f"Generated by `tools/report_profile.py` on {date.today().isoformat()}. The NominalAnalog profile is "
        "synthetic: its noise, distortion, mismatch, and crosstalk are calibrated to the datasheet's typical "
        "values, not measured from a device. Meeting these targets does not make the model sound like a "
        "particular AK4522.", "",
        "Conditions: `HostProcessor` at 44.1 kHz host and DAC rates, `AnalogOptions::nominal()` (noise, "
        "distortion equal 2nd/3rd, fixed mismatch, capacitive crosstalk), 997 Hz tone, left channel, "
        "measurement band 10 Hz to 20 kHz, levels relative to a full-scale sine. Isolation and mismatch are "
        "measured by the C++ tests (see validation.md).", "",
        "| Quantity | Evidence | Datasheet min (dB) | Datasheet typ (dB) | Measured (dB) | Project target |",
        "| -------- | -------- | -----------------: | -----------------: | ------------: | -------------- |",
    ]
    for name, ev, mn, typ, value, target in rows:
        lines.append(f"| {name} | {ev} | {mn} | {typ} | {value:.2f} | {target} |")
    lines += ["", f"Unweighted S/N (10 Hz to 20 kHz, zero input): {snr_unweighted:.2f} dB.", "",
              "## S/(N+D) versus level", "",
              "The datasheet gives S/(N+D) at one level without a qualifier for the DAC row; 0 dBFS is the "
              "declared level (P-96). Below full scale the noise floor dominates.", "",
              "| Level (dBFS) | S/(N+D) (dB) |", "| -----------: | -----------: |"]
    for lvl, x in sweep.items():
        lines.append(f"| {lvl} | {metrics.sinad(x, RATE, TONE):.2f} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT.read_text())
    return 0


if __name__ == "__main__":
    sys.exit(main())
