"""Design the three de-emphasis filters and write their coefficients and report.

Reference: H(s) = (1 + s*15e-6) / (1 + s*50e-6), unity at DC (D-E01, I-E01).
Each selection (32, 44.1, 48 kHz) gets a first-order digital section

    H(z) = k (1 - z0 z^-1) / (1 - p z^-1),   k = (1 - p) / (1 - z0)

so DC gain is exactly 1. The zero z0 and pole p minimize the largest
magnitude error in dB against the reference from 20 Hz to the lesser of
20 kHz and 0.45 times the selection's rate (P-61), starting from the
prewarped bilinear transform. Phase error is reported, not constrained:
no causal low-order digital section follows the analog phase near its
Nyquist frequency (P-60).

    cd tools && uv run python design_deemphasis.py

Writes src/dsp/deemphasis_coefficients.inc and src/dsp/deemphasis_design.json.
"""

from __future__ import annotations

import hashlib
import json
import platform
import sys
from pathlib import Path

import numpy as np
import scipy
from scipy import signal
from scipy.optimize import minimize

TAU_POLE = 50e-6    # D-E01
TAU_ZERO = 15e-6    # D-E01
RATES = (32000.0, 44100.0, 48000.0)  # order written to the .inc file
MAX_ERROR_DB = 0.1  # P-61
FIT_POINTS = 2000
CHECK_POINTS = 50000

ROOT = Path(__file__).resolve().parent.parent
OUT_INC = ROOT / "src/dsp/deemphasis_coefficients.inc"
OUT_JSON = ROOT / "src/dsp/deemphasis_design.json"


def reference(f: np.ndarray) -> np.ndarray:
    s = 2j * np.pi * f
    return (1 + s * TAU_ZERO) / (1 + s * TAU_POLE)


def band(fs: float, points: int) -> np.ndarray:
    return np.geomspace(20.0, min(20000.0, 0.45 * fs), points)


def section(zero: float, pole: float) -> tuple[np.ndarray, np.ndarray]:
    k = (1.0 - pole) / (1.0 - zero)
    return np.array([k, -k * zero]), np.array([1.0, -pole])


def errors(b: np.ndarray, a: np.ndarray, fs: float, f: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    _, h = signal.freqz(b, a, worN=f, fs=fs)
    ratio = h / reference(f)
    return 20 * np.log10(np.abs(ratio)), np.degrees(np.angle(ratio))


def fit(fs: float) -> dict:
    b0, a0 = signal.bilinear([TAU_ZERO, 1.0], [TAU_POLE, 1.0], fs)
    start = [-b0[1] / b0[0], -a0[1]]
    f = band(fs, FIT_POINTS)

    def cost(params):
        zero, pole = params
        if not (-1.0 < pole < 1.0) or zero >= 1.0:
            return 1e9
        mag, _ = errors(*section(zero, pole), fs, f)
        return float(np.max(np.abs(mag)))

    result = minimize(cost, start, method="Nelder-Mead",
                      options={"xatol": 1e-13, "fatol": 1e-13, "maxiter": 20000})
    zero, pole = result.x
    b, a = section(zero, pole)

    dense = band(fs, CHECK_POINTS)
    mag, phase = errors(b, a, fs, dense)
    bilinear_mag, _ = errors(b0, a0, fs, dense)
    return {
        "rate_hz": fs,
        "band_hz": [20.0, float(dense[-1])],
        "b0": float(b[0]), "b1": float(b[1]), "a1": float(a[1]),
        "zero": float(zero), "pole": float(pole),
        "dc_gain": float((b[0] + b[1]) / (1.0 + a[1])),
        "max_magnitude_error_db": float(np.max(np.abs(mag))),
        "max_phase_error_deg": float(np.max(np.abs(phase))),
        "phase_error_at_band_edge_deg": float(phase[-1]),
        "bilinear_max_magnitude_error_db": float(np.max(np.abs(bilinear_mag))),
    }


def main() -> int:
    sets = [fit(fs) for fs in RATES]
    flat = [v for s in sets for v in (s["b0"], s["b1"], s["a1"])]
    digest = hashlib.sha256(np.array(flat, dtype="<f8").tobytes()).hexdigest()

    lines = [
        "// Generated by tools/design_deemphasis.py. Do not edit.",
        "// First-order sections b0 b1 a1 (a0 = 1) for 32, 44.1, and 48 kHz, in that order.",
        f"// SHA-256 of the little-endian doubles: {digest}",
        "// Fitted to the 50/15 us reference; not AKM's coefficients (P-60, P-61).",
    ]
    for s in sets:
        lines.append(f"// {s['rate_hz']:.0f} Hz: max magnitude error {s['max_magnitude_error_db']:.4f} dB")
        lines += [f"{v.hex()}, // {v:+.17e}" for v in (s["b0"], s["b1"], s["a1"])]
    OUT_INC.write_text("\n".join(lines) + "\n", encoding="utf-8")

    report = {
        "generator": "tools/design_deemphasis.py",
        "reference": "H(s) = (1 + s*15e-6) / (1 + s*50e-6)",
        "method": "first-order section with exact unity DC gain; Nelder-Mead minimax of "
                  "magnitude error in dB on a log grid, starting from the prewarped bilinear transform",
        "limit_db": MAX_ERROR_DB,
        "sets": sets,
        "precision": "IEEE 754 double",
        "sha256_le_f8": digest,
        "versions": {"python": sys.version.split()[0], "numpy": np.__version__,
                     "scipy": scipy.__version__, "platform": platform.platform()},
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")

    ok = True
    for s in sets:
        passed = s["max_magnitude_error_db"] <= MAX_ERROR_DB and abs(s["pole"]) < 1.0
        ok &= passed
        print(f"{s['rate_hz']:.0f} Hz: magnitude {s['max_magnitude_error_db']:.4f} dB "
              f"(bilinear {s['bilinear_max_magnitude_error_db']:.3f}), phase {s['max_phase_error_deg']:.2f} deg, "
              f"pole {s['pole']:.6f} {'pass' if passed else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
